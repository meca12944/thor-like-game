def grid(zid, nx, ny, skip=(), base=3):
    z = zb[zid]
    for j in range(ny):
        for i in range(nx):
            x = z['x'] + int((i + .5) * z['w'] / nx) + (5 if j % 2 else -5); y = z['y'] + int((j + .5) * z['h'] / ny)
            if any(abs(x - a) < 14 and abs(y - b) < 14 for a, b in skip): continue
            big = base >= 3 and (i + j * nx) % 5 == 2  # 들판·넓은 방: 다섯 무리에 하나는 큰 무리
            size = '큰 5~6' if big else ('보통 3~4' if base >= 3 else '작은 2~3')
            mk('mob', f'몹 무리 {size}', zid, x, y, '', '팀 제안: 위치·크기 (마물 종류는 기획 뒤)')
