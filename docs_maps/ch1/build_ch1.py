def inpoly(x, y, poly, pad=0):
    xs = [p[0] for p in poly]; ys = [p[1] for p in poly]
    if not (min(xs) - pad <= x <= max(xs) + pad and min(ys) - pad <= y <= max(ys) + pad): return False
    c = False; n = len(poly)
    for i in range(n):
        (x1, y1), (x2, y2) = poly[i], poly[(i + 1) % n]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1 + 1e-9) + x1: c = not c
    if c or not pad: return c
    return any(((x - px) ** 2 + (y - py) ** 2) < pad * pad for px, py in poly) or any(inpoly(x + dx, y + dy, poly) for dx, dy in ((pad, 0), (-pad, 0), (0, pad), (0, -pad)))
