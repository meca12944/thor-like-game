# 새 그록 주인공 아틀라스 (사장님 10-25 「팀장 추천대로 컨펌」 순서표 9 게임 연결): H8 형식 그대로 → hero_grok.json + hero_grok_<n>.webp
# 그림: motion_lab/grok_hero/final_stampedB2 (게임 크기 144, 발 (128,189), 얼굴 B + 앞머리). 게임 방향 이름: down=정면, dr=↘, right=→, up=↗(비스듬한 뒷모습), n=↑(똑바른 뒷모습), left = 오른쪽 뒤집기(H8.left=0)
import os,json,glob
from PIL import Image
R=os.path.dirname(os.path.abspath(__file__));G=os.path.join(R,'../../../motion_lab/grok_hero');SRC=f'{G}/final_stampedB2'
IDLE=json.load(open(f'{G}/idle_pick.json'))   # 걷기 중 두 발이 가장 모인 장
idx=lambda p:int(os.path.basename(p)[:3])
M=json.load(open(f'{G}/moves/moves.json'))
D={'down':'down','dr':'dr','right':'right','up':'ur','n':'up'}          # 게임 방향 → 우리 폴더 방향
CL={}
for g,o in D.items():
    CL[f'idle_{g}']=[(f'walk_{o}',idx(IDLE[o]),60)]
    CL[f'walk_{g}']=[(f'walk_{o}',i,6) for i in range(len(glob.glob(f'{SRC}/walk_{o}/*.png')))]
    CL[f'run_{g}']=[(f'run_{o}',i,4) for i in range(len(glob.glob(f'{SRC}/run_{o}/*.png')))]
def mv(name,folder,ticks=None):
    t=ticks or M[folder.split('/')[-1] if folder in M else folder]['ticks'];CL[name]=[(folder,i,tt) for i,tt in enumerate(t)]
for g,o in (('down','down'),('dr','dr'),('right','right'),('up','ur')):
    mv(f'dash_{g}',f'dash_{o}',M[f'dash_{o if o!="ur" else "ur"}']['ticks']);mv(f'jump_{g}',f'jump_{o}',M[f'jump_{o}']['ticks'])
for g,o in (('down','down'),('right','right'),('up','up')): mv(f'hurt_{g}',f'hurt_{o}',M[f'hurt_{o}']['ticks'])
CL['hurtys_right']=CL['hurt_right'];mv('death_right','death_right',M['death_right']['ticks']);mv('rjump_right','rjump_right',M['rjump_right']['ticks'])
DUR=[14,18,27]   # H8.combo dur(틱) — 남는 틱은 공격 자세에
for i in (1,2,3):
    for g,o in (('down','down'),('right','right'),('up','up')):
        t=list(M[f'atk{i}_{o}']['ticks']);t[-1]=max(1,DUR[i-1]-sum(t[:-1]));CL[f'hit{i}_{g}']=[(f'atk{i}_{o}',j,tt) for j,tt in enumerate(t)]
CL['hold_right']=[(CL['hit1_right'][-1][0],CL['hit1_right'][-1][1],30)];CL['rec1_right']=CL['hit2_right'][-1:];CL['rec2_right']=CL['hit3_right'][-1:]
# 칸 모으기(같은 그림은 한 칸), 줄 맞춰 시트에 쌓기
cells=[];key2cell={}
def cell_of(folder,i):
    k=(folder,i)
    if k not in key2cell:
        im=Image.open(f'{SRC}/{folder}/{i:03d}.png').convert('RGBA');b=im.getbbox();key2cell[k]=len(cells);cells.append((im.crop(b),b))
    return key2cell[k]
anims={n:[[None,cell_of(f,i),t] for f,i,t in v] for n,v in CL.items()}
SW=2048;sheets=[];pos=[];x=y=rowh=0;cur=[]
for ci,(im,b) in enumerate(cells):
    if x+im.width>SW: x=0;y+=rowh+1;rowh=0
    if y+im.height>2048: sheets.append(cur);cur=[];x=y=rowh=0
    cur.append((ci,x,y));pos.append((len(sheets),x,y));x+=im.width+1;rowh=max(rowh,im.height)
sheets.append(cur)
out_cells=[[] for _ in sheets];local={}
for si,lst in enumerate(sheets):
    W=max(x+cells[ci][0].width for ci,x,y in lst);H=max(y+cells[ci][0].height for ci,x,y in lst);S=Image.new('RGBA',(W,H))
    for ci,x,y in lst:
        im,b=cells[ci];S.paste(im,(x,y));local[ci]=(si,len(out_cells[si]));out_cells[si].append([x,y,im.width,im.height,128-b[0],189-b[1]])
    S.save(f'{R}/hero_grok_{si}.webp',lossless=True)
for n,v in anims.items():
    for e in v: si,c=local[e[1]];e[0]=si;e[1]=c
J=dict(_doc='GENERATED by handoff/claude/hero_grok_v1/build_atlas.py — 새 그록 주인공(5.5등신, 게임 키 144 art px). sheets 번호는 이 파일 안 기준(apply.py가 H8 sheets 뒤에 붙이며 번호를 옮김). anchor = 발 (128,189).',
       figH=144,sheets=[f'anim/hero_grok_{i}.webp' for i in range(len(sheets))],cells=out_cells,anims=anims,
       jumpPh={**{f'jump_{g}':[[0,1,2],[3],[4,5,6]] for g in ('down','dr','right','up')},'rjump_right':[[0,1],[2],[3,4,5]]})
json.dump(J,open(f'{R}/hero_grok.json','w'),separators=(',',':'))
print('시트',len(sheets),[ (Image.open(f"{R}/hero_grok_{i}.webp").size) for i in range(len(sheets))],'칸',len(cells),'동작',len(anims))
