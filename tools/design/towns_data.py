def npc(id,name,role,pers,greet,shop=None): 
    d=dict(id=id,name=name,role=role,personality=pers,greeting=greet)
    if shop: d['shop']=shop
    return d
def q(id,giver,title,typ,story,objective,reward,req=None,chain=None):
    d=dict(id=id,giver=giver,title=title,type=typ,story=story,objective=objective,reward=reward)
    if req: d['requires']=req
    if chain: d['chain']=chain
    return d

