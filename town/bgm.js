/* BGM manager for the town demo (Web Audio, seamless loops, crossfades).
 * Self-contained: watches window.__game, never touches game logic.
 *   - starts only after the first user input (browser autoplay rules)
 *   - town -> 'town_a_fountain', champion fight -> 'battle_champion', dive -> 'underwater',
 *     champion defeated -> 'jingle_victory' then back to the town theme
 *   - keys (only when the key is not bound to a game action):  B = mute/unmute,  - / = volume,  N = jukebox (next track)
 *   - URL: ?bgm=<track id> forces a track (e.g. ?bgm=battle_boss), ?bgm=off disables music
 *   - API for the full game: BGM.scene('boss'|'boss2'|...), BGM.play(id), BGM.jingle(id), BGM.setVolume(0..1), BGM.toggleMute()
 * Tracks + loop points: ../audio/bgm/bgm.json (generated by tools/music/render.py).
 */
(function () {
  'use strict';
  const BASE = '../audio/bgm/';
  const LS = 'townDemo.bgm';
  const FADE = 1.2;
  // situation -> track (for the full game; the demo uses town / champion / dive / victory)
  const SCENES = {
    title: 'title', world: 'worldmap', town: 'town_a_fountain', shop: 'forge_shop', ruin: 'town_ruin',
    champion: 'battle_champion', boss: 'battle_boss', boss2: 'battle_boss_phase2', aslan: 'battle_aslan', kairen: 'user_ref_01', kairenAlt: 'battle_kairen',
    demon: 'demon_field', awaken: 'demon_awaken', dive: 'underwater', gameover: 'jingle_gameover', victory: 'jingle_victory',
    area1: 'area01_forest', area2: 'area02_cave', area3: 'area03_desert', area4: 'area04_pyramid', area5: 'area05_coral_sea',
    area6: 'area06_cliff', area7: 'area07_volcano', area8: 'area08_thunder_tower', area9: 'area09_dark_temple', area10: 'area10_dragon_nest',
    townA: 'town_a_fountain', townB: 'town_b_watermill', townH: 'town_h_mine', townG: 'town_g_bazaar', townF: 'town_f_harbor',
    townE: 'town_e_forge', townC: 'town_c_snow_lodge', townD: 'town_d_capital',
    endTrue: 'ending_true', endLight: 'ending_light', endTragic: 'ending_tragic', endDemon: 'ending_demon',
  };
  const Q = new URLSearchParams(location.search);
  const forced = Q.get('bgm');
  let st = { vol: 0.6, muted: false };
  try { Object.assign(st, JSON.parse(localStorage.getItem(LS) || '{}')); } catch (e) {}
  const save = () => { try { localStorage.setItem(LS, JSON.stringify(st)); } catch (e) {} };

  let ctx = null, master = null, man = null, manP = null;
  const bufs = {}, loading = {};
  let cur = null;          // {id, src, gain}
  let want = null;         // track id the game state asks for
  let jingleUntil = 0, jukebox = -1, started = false, failed = false;

  // ---------- tiny toast ----------
  const toast = document.createElement('div');
  toast.style.cssText = 'position:fixed;left:50%;top:10px;transform:translateX(-50%);padding:4px 12px;background:#0b0b14cc;color:#ffe08a;' +
    'font:bold 13px sans-serif;border:2px solid #e8d6b0;border-radius:4px;pointer-events:none;opacity:0;transition:opacity .4s;z-index:50;white-space:nowrap';
  let toastT = 0;
  function say(t) { toast.textContent = t; toast.style.opacity = 1; clearTimeout(toastT); toastT = setTimeout(() => toast.style.opacity = 0, 2200); }
  (document.body ? Promise.resolve() : new Promise(r => addEventListener('DOMContentLoaded', r))).then(() => document.body.appendChild(toast));

  function manifest() {
    if (!manP) manP = fetch(BASE + 'bgm.json').then(r => { if (!r.ok) throw new Error('bgm.json ' + r.status); return r.json(); })
      .then(j => (man = j)).catch(e => { failed = true; console.warn('[bgm] manifest unavailable:', e.message); return null; });
    return manP;
  }
  function load(id) {
    if (bufs[id]) return Promise.resolve(bufs[id]);
    if (loading[id]) return loading[id];
    return (loading[id] = manifest().then(m => {
      if (!m || !m[id]) throw new Error('unknown track ' + id);
      return fetch(BASE + m[id].file);
    }).then(r => { if (!r.ok) throw new Error(id + ' ' + r.status); return r.arrayBuffer(); })
      .then(ab => new Promise((res, rej) => ctx.decodeAudioData(ab, res, rej)))
      .then(b => (bufs[id] = b))
      .catch(e => { console.warn('[bgm] cannot play', id, e && e.message || e); delete loading[id]; throw e; }));
  }
  function applyVol() { if (master) master.gain.setTargetAtTime(st.muted ? 0 : st.vol, ctx.currentTime, 0.05); }

  function stopCur(fade) {
    if (!cur) return;
    const c = cur, t = ctx.currentTime;
    c.gain.gain.cancelScheduledValues(t); c.gain.gain.setValueAtTime(c.gain.gain.value, t); c.gain.gain.linearRampToValueAtTime(0, t + fade);
    try { c.src.stop(t + fade + 0.05); } catch (e) {}
    cur = null;
  }
  // play a track: loops use their intro + loopStart/loopEnd; one-shots (jingles) play once
  function play(id, opt = {}) {
    if (!ctx || failed) { want = id; return; }
    if (cur && cur.id === id && !opt.restart) return;
    const token = (play.token = (play.token || 0) + 1);
    load(id).then(buf => {
      if (token !== play.token) return;         // a newer request won
      const info = man[id], t = ctx.currentTime, fade = opt.fade ?? FADE;
      const src = ctx.createBufferSource(); src.buffer = buf;
      if (info.loop) { src.loop = true; src.loopStart = info.loopStart; src.loopEnd = Math.min(info.loopEnd, buf.duration); }
      const g = ctx.createGain(); g.gain.setValueAtTime(0.0001, t); g.gain.linearRampToValueAtTime(1, t + (opt.fadeIn ?? Math.min(fade, 0.6)));
      src.connect(g).connect(master);
      stopCur(fade);
      src.start(t + 0.02);
      cur = { id, src, gain: g, oneShot: !info.loop };
      if (!info.loop) { jingleUntil = performance.now() + buf.duration * 1000; src.onended = () => { if (cur && cur.src === src) { cur = null; jingleUntil = 0; } }; }
      if (!opt.quiet) say('♪ ' + info.title + (info.en ? '  · ' + info.en : ''));
    }).catch(() => {});
  }
  function jingle(id) { play(id, { fade: 0.4, fadeIn: 0.02, restart: true }); }

  // ---------- game state -> music ----------
  let fightT = 0, lastBoarDead = null;
  function desired() {
    if (forced && forced !== 'off') return forced;
    const g = window.__game;
    if (!g || !g.ready) return SCENES.town;
    if (g.uw) return SCENES.dive;
    const b = g.boar, h = g.hero;
    if (b && h) {
      if (lastBoarDead === false && b.dead && fightT > 0) { fightT = 0; lastBoarDead = true; jingle(SCENES.victory); return null; }
      lastBoarDead = !!b.dead;
      if (!b.dead) {
        const d = Math.hypot(b.x - h.x, b.y - h.y);
        if (d < 340 || b.hp < b.maxHp) fightT = 4;          // engaged
      }
      if (fightT > 0) return b.dead ? SCENES.town : SCENES.champion;
    }
    return SCENES.town;
  }
  setInterval(() => {
    if (!started || jukebox >= 0) return;
    fightT = Math.max(0, fightT - 0.25);
    const g = window.__game, b = g && g.boar, h = g && g.hero;
    if (b && h && !b.dead && fightT > 0 && Math.hypot(b.x - h.x, b.y - h.y) < 520) fightT = Math.max(fightT, 1);
    const id = desired();
    if (id === null || performance.now() < jingleUntil) return;
    if (!cur || cur.id !== id) play(id);
  }, 250);

  // ---------- start on first input ----------
  function start() {
    if (started || forced === 'off') return;
    const AC = window.AudioContext || window.webkitAudioContext;
    if (!AC) { failed = true; return; }
    started = true;
    ctx = new AC(); master = ctx.createGain(); master.gain.value = st.muted ? 0 : st.vol; master.connect(ctx.destination);
    if (ctx.state === 'suspended') ctx.resume();
    manifest().then(() => { if (want) play(want); });
    removeEventListener('keydown', start, true); removeEventListener('pointerdown', start, true); removeEventListener('touchend', start, true);
  }
  addEventListener('keydown', start, true); addEventListener('pointerdown', start, true); addEventListener('touchend', start, true);

  // ---------- keys (B mute, -/= volume, N jukebox); skipped when the game uses that key or is rebinding ----------
  function gameUses(code) {
    const c = window.__game && window.__game.ctl;
    if (!c) return false;
    if (c.rebind) return true;
    try { return Object.values(c.KEYMAP).some(list => list.includes(code)); } catch (e) { return false; }
  }
  addEventListener('keydown', e => {
    if (e.repeat || e.ctrlKey || e.metaKey || e.altKey) return;
    const code = e.code;
    if (!['KeyB', 'KeyN', 'Minus', 'Equal', 'NumpadSubtract', 'NumpadAdd'].includes(code) || gameUses(code)) return;
    if (code === 'KeyB') { st.muted = !st.muted; applyVol(); save(); say(st.muted ? '♪ 음악 끔 (B)' : '♪ 음악 켬 · 볼륨 ' + Math.round(st.vol * 100) + '%'); }
    else if (code === 'Minus' || code === 'NumpadSubtract' || code === 'Equal' || code === 'NumpadAdd') {
      st.vol = Math.max(0, Math.min(1, Math.round((st.vol + (code === 'Minus' || code === 'NumpadSubtract' ? -0.1 : 0.1)) * 10) / 10));
      st.muted = false; applyVol(); save(); say('♪ 볼륨 ' + Math.round(st.vol * 100) + '%  (- / =)');
    } else if (code === 'KeyN' && man) {
      const ids = Object.keys(man); jukebox = (jukebox + 1) % (ids.length + 1);
      if (jukebox === ids.length) { jukebox = -1; say('♪ 주크박스 끝 → 장면 음악'); cur && stopCur(0.6); }
      else play(ids[jukebox], { restart: true }), setTimeout(() => say('♪ [' + (jukebox + 1) + '/' + ids.length + '] ' + man[ids[jukebox]].title + ' (N 다음)'), 50);
    }
  });

  window.BGM = {
    SCENES, play: id => { jukebox = -1; play(id); }, jingle, scene: name => play(SCENES[name] || name),
    setVolume(v) { st.vol = Math.max(0, Math.min(1, v)); applyVol(); save(); }, toggleMute() { st.muted = !st.muted; applyVol(); save(); },
    get state() { return { started, failed, current: cur && cur.id, vol: st.vol, muted: st.muted, ctx: ctx && ctx.state, loaded: Object.keys(bufs) }; },
  };
})();
