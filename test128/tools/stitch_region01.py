# Semi-open world (owner 10-23 「세미 오픈월드 이스8처럼」): stitch 바람길 (field00) + 시작의 숲 (field01) into ONE seamless map.
# Source maps stay editable in maps/src/; this writes maps/field00.json (id kept: town gate, Linette, tests all use 'field00').
# field01 sits at x+56 (its old mapPos). The two seam exits are dropped, so walking east just continues. world.js maps the old
# id 'field01' (dungeon / boss exits, world-map node) to this map with spawn names prefixed 'f01_'.
# areas[] = the two named parts; world.js shows the area name (no fade) and auto-saves on the first visit.
import json, os
D = os.path.join(os.path.dirname(__file__), '..', 'maps')
a = json.load(open(os.path.join(D, 'src', 'field00.json'))); b = json.load(open(os.path.join(D, 'src', 'field01.json')))
DX = 56; W = a['w'] + b['w']; H = max(a['h'], b['h'])
assert DX == a['w'] and b['mapPos'] == [DX, 0]
ga = [r.ljust(a['w'], '#') for r in a['ground']] + ['#' * a['w']] * (H - a['h'])
gb = [r.ljust(b['w'], '#') for r in b['ground']] + ['#' * b['w']] * (H - b['h'])
legend = dict(b['legend']); legend.update(a['legend'])
seam = lambda o, to: o['type'] == 'exit' and o['to'] == to
objs = [o for o in a['objects'] if not seam(o, 'field01')]
for o in b['objects']:
    if seam(o, 'field00'): continue
    o = dict(o); o['x'] = o['x'] + DX; objs.append(o)
spawns = {k: v for k, v in a['spawns'].items() if k != 'east'}
for k, v in b['spawns'].items(): spawns['f01_' + k] = [v[0] + DX] + v[1:]
out = {k: a[k] for k in ('id', 'type', 'area', 'region', 'mapPos', 'title', 'bgm', 'battleBgm', 'tileset', 'tile')}
out.update(name='1지역 — 바람길 · 시작의 숲', w=W, h=H, legend=legend, solid=sorted(set(a['solid']) | set(b['solid'])), spawns=spawns,
           areas=[{'id': 'a1_windroad', 'name': '바람길', 'sub': '시작 마을 외곽', 'x': 0, 'y': 0, 'w': DX, 'h': H},
                  {'id': 'a1_forest', 'name': '시작의 숲', 'sub': '던전 가는 길', 'x': DX, 'y': 0, 'w': b['w'], 'h': H}],
           objects=objs, ground=[ga[y] + gb[y] for y in range(H)], note='GENERATED by tools/stitch_region01.py from maps/src/field00.json + field01.json — edit the sources')
with open(os.path.join(D, 'field00.json'), 'w') as f: json.dump(out, f, ensure_ascii=False, indent=1)
print('field00.json', W, 'x', H, len(objs), 'objects')
