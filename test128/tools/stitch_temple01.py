# Semi-open world (owner 10-23 「추천대로」): 고대 숲 신전 B1 + B2 become ONE seamless dungeon map (no stairs fade between floors).
# Sources stay editable in maps/src/; this writes maps/dungeon01_b1.json (id kept: field / boss exits, quests use it).
# B2 sits at x+46 (its old mapPos). The B1 stairs-down room and the B2 stairs-up room are joined by a sloping corridor (rows 3-4);
# both stair objects are removed. world.js maps the old id 'dungeon01_b2' to this map with spawn names prefixed 'b2_'.
# The boss room (boss01) stays behind its door — the only fade inside the temple.
import json, os
D = os.path.join(os.path.dirname(__file__), '..', 'maps')
a = json.load(open(os.path.join(D, 'src', 'dungeon01_b1.json'))); b = json.load(open(os.path.join(D, 'src', 'dungeon01_b2.json')))
DX = b['mapPos'][0]; W = DX + b['w']; H = max(a['h'], b['h'])
rows = [list((a['ground'][y] if y < a['h'] else '').ljust(DX, '#') + (b['ground'][y] if y < b['h'] else '').ljust(b['w'], '#')) for y in range(H)]
def find(ch, x0, x1):
    return [(x, y) for y in range(H) for x in range(x0, x1) if rows[y][x] == ch]
(vx, vy), = find('V', 0, DX); (ux, uy), = find('U', DX, W)
rows[vy][vx] = '.'; rows[uy][ux] = '.'
# corridor: from the east wall of the B1 stairs room to the west wall of the B2 stairs room, two tiles tall, cracked floor = the slope down
x0 = vx; x1 = ux
while rows[vy][x0 + 1] != '#': x0 += 1
while rows[uy][x1 - 1] != '#': x1 -= 1
for x in range(x0 + 1, x1):
    for y in (vy, vy + 1): rows[y][x] = '%' if (x - x0) % 3 == 0 else '.'
for x in (x0 + 4, x1 - 4): rows[vy - 1][x] = 't'          # two torches along the slope
legend = dict(a['legend'])
objs = [dict(o) for o in a['objects']]
for o in b['objects']: o = dict(o); o['x'] += DX; objs.append(o)
objs.append({'type': 'sign', 'x': x0 + 2, 'y': vy - 0.4, 'walk': True, 'text': '아래층(B2)으로 이어지는 비탈길.\n동쪽 끝 봉인된 문 너머가 골렘의 방.'})
bx, by = [(x, y) for y in range(H) for x in range(DX, W) if rows[y][x] == 'B'][0]
objs.append({'type': 'waystone', 'id': 'ws_temple_b2', 'x': bx - 2, 'y': by + 2, 'name': '골렘의 방 앞 비석'})   # rule: a waystone before every boss
spawns = dict(a['spawns'])
for k, v in b['spawns'].items(): spawns['b2_' + k] = [v[0] + DX] + v[1:]
links = {'stairs_up': a['links']['stairs_up'], 'boss_door': b['links']['boss_door']}
out = {k: a[k] for k in ('id', 'region', 'mapPos', 'type', 'area', 'title', 'bgm', 'tileset', 'tile')}
out.update(name='고대 숲 신전', dark=round((a.get('dark', .55) + b.get('dark', .62)) / 2, 2), w=W, h=H, legend=legend, solid=sorted(set(a['solid']) | set(b['solid'])),
           spawns=spawns, links=links, gateNeeds=b.get('gateNeeds'), chests={**a.get('chests', {}), **{f"{int(k.split(',')[0]) + DX},{k.split(',')[1]}": v for k, v in b.get('chests', {}).items()}},
           keys=a.get('keys', {}), areas=[{'id': 't1_b1', 'name': '고대 숲 신전 · 위층', 'sub': '열쇠와 잠긴 문', 'x': 0, 'y': 0, 'w': x0 + 3, 'h': H},
                                          {'id': 't1_b2', 'name': '고대 숲 신전 · 아래층', 'sub': '레버 두 개와 봉인된 문', 'x': x0 + 3, 'y': 0, 'w': W - x0 - 3, 'h': H}],
           objects=objs, ground=[''.join(r) for r in rows], note='GENERATED by tools/stitch_temple01.py from maps/src/dungeon01_b1.json + dungeon01_b2.json — edit the sources')
with open(os.path.join(D, 'dungeon01_b1.json'), 'w') as f: json.dump(out, f, ensure_ascii=False, indent=1)
print('dungeon01_b1.json', W, 'x', H, len(objs), 'objects; slope', x0 + 1, '..', x1 - 1, 'rows', vy, vy + 1)
for r in out['ground']: print(r)
