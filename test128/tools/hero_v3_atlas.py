# hero_v3_atlas.py — v3 hero motions -> assets/anim/hero8_*.webp + hero8.json (same H8 format as hero8_atlas.py, + per-frame fx layers)
#  idle=px_idle4, walk=px_walk5, run=px_run4, hit1-3=px_combo3arc (+fx_, combo3_arc.json), cast_s1/s2/s3=px_cast_proj/wave/slam (+magic circle back/front),
#  dash=px_dash4, hurt=px_hurt4.  Dirs right/down/up (left = runtime mirror). Anchor = locked root (feet): 224x176 -> (112,160), combo 304x256 -> (152,200), cast fx 288x248 -> (144,208).
import json,os,glob,numpy as np
from PIL import Image
VID='/workspace/town-demo/char_v4/pixellab/hero/vid'; V3=VID+'/v3'; MC=V3+'/fx/magic_circle'; OUT='/workspace/town-demo/assets/anim'
M=json.load(open(V3+'/motion_v3.json'))['tags']; MD=json.load(open(V3+'/motion_v3_dh.json'))['tags']
CA=json.load(open(V3+'/combo3_arc.json'))['combos']; MCJ=json.load(open(MC+'/fx_magic_circle.json'))
DIRS=['right','down','up']; frames={}
def add(sheet,path,root):
    f=np.asarray(Image.open(path).convert('RGBA')); a=f[...,3]>0
    if not a.any(): return None
    ys,xs=np.where(a); y0,y1,x0,x1=ys.min(),ys.max()+1,xs.min(),xs.max()+1
    L=frames.setdefault(sheet,[])
    for j,(k,*_) in enumerate(L):
        if k==path: return [sheet,j]
    L.append((path,np.ascontiguousarray(f[y0:y1,x0:x1]),int(root[0]-x0),int(root[1]-y0))); return [sheet,len(L)-1]
R0=(112,160); RC=(152,200); RF=(144,208)
anims={}; cast={}; combo=[]
for d in DIRS:
    def seq(sheet,tag,ticks):
        fs=sorted(p for p in glob.glob(f'{VID}/px_{tag}/*.png') if not os.path.basename(p).startswith('fx_'))
        assert len(fs)==len(ticks),(tag,len(fs),len(ticks)); return [add(sheet,p,R0)+[t] for p,t in zip(fs,ticks)]
    anims['idle_'+d]=seq('idle',f'idle4_{d}',M[f'idle4_{d}']['ticks'])
    anims['walk_'+d]=seq('walk',f'walk5_{d}',M[f'walk4_{d}']['ticks'] if len(glob.glob(f'{VID}/px_walk5_{d}/*.png'))==12 else [4]*len(glob.glob(f'{VID}/px_walk5_{d}/*.png')))
    anims['run_'+d]=seq('run',f'run4_{d}',M[f'run4_{d}']['ticks'])
    anims['dash_'+d]=seq('dash',f'dash4_{d}',MD[f'dash4_{d}']['ticks'])
    anims['hurt_'+d]=seq('hurt',f'hurt4_{d}',MD[f'hurt4_{d}']['ticks'])
    C=CA[d]
    for hit in (1,2,3):
        L=[]
        for k,fi in enumerate(C['frames']):
            if fi['hit']!=hit: continue
            e=add('atk',f'{VID}/px_combo3arc_{d}/{k:03d}.png',RC)+[fi['ticks']]
            fx=add('atkfx',f'{VID}/px_combo3arc_{d}/fx_{k:03d}.png',RC)
            L.append(e+(fx if fx else []))
        anims[f'hit{hit}_'+d]=L
    anims['rec1_'+d]=[anims['hit1_'+d][-1][:2]+[12]]; anims['rec2_'+d]=[anims['hit2_'+d][-1][:2]+[12]]
    anims['hold_'+d]=[anims['hit3_'+d][0][:2]+[1]]
    for n,t in (('s1','cast_proj'),('s2','cast_wave'),('s3','cast_slam')):
        tg=f'{t}_{d}'; J=MCJ['tags'][tg]; L=seq('cast',tg,M[tg]['ticks'])
        for e,fr in zip(L,J['frames']):
            b=add('castfx',f"{MC}/{fr['back']}",RF); f_=add('castfx',f"{MC}/{fr['front']}",RF)
            e+= (b or [-1,-1])+(f_ or [-1,-1])
        anims[f'cast_{n}_'+d]=L
        ph=J.get('phases',{'windup':[0,3],'charge':[4,7],'release':[8,10],'recover':[11,14]})
        cast[f'{n}_{d}']={'a':ph['charge'][0],'rs':ph['release'][0],'e':ph['recover'][0],'n':len(L)}
J0=CA['right']; tick0=0
for hit in (1,2,3):
    fr=[f for f in J0['frames'] if f['hit']==hit]; dur=sum(f['ticks'] for f in fr)
    h=J0['hits'][f'hit{hit}']['event_tick']-tick0; c=J0['cancel'][f'hit{hit}']['cancel_from_tick']-tick0
    stop=[f['ticks'] for f in fr if f['phase']=='hitstop'][0]
    combo.append({'dur':dur,'hit':h,'cancel':c,'stop':stop,'abs_hit':J0['hits'][f'hit{hit}']['event_tick'],'abs_cancel':J0['cancel'][f'hit{hit}']['cancel_from_tick']}); tick0+=dur
sheets={}; cells={}; total=0
for sh,L in frames.items():
    order=sorted(range(len(L)),key=lambda j:-L[j][1].shape[0]); x=y=rowh=0; pos={}
    for j in order:
        h,w=L[j][1].shape[:2]
        if x+w>2048: x=0; y+=rowh+1; rowh=0
        pos[j]=(x,y); x+=w+1; rowh=max(rowh,h)
    H=y+rowh; Wd=max(p[0]+L[j][1].shape[1] for j,p in pos.items()); im=Image.new('RGBA',(Wd,H))
    for j,(px,py) in pos.items(): im.paste(Image.fromarray(L[j][1]),(px,py))
    fn=f'hero8_{sh}.webp'; im.save(f'{OUT}/{fn}','WEBP',lossless=True,quality=100,method=6); total+=os.path.getsize(f'{OUT}/{fn}')
    cells[sh]=[[pos[j][0],pos[j][1],L[j][1].shape[1],L[j][1].shape[0],L[j][2],L[j][3]] for j in range(len(L))]; sheets[sh]=f'anim/{fn}'
    print(sh,len(L),im.size)
SH=list(sheets); ix=lambda s:SH.index(s)
def res(e):
    o=[ix(e[0]),e[1],e[2]]; r=e[3:]
    while r:
        if r[0]==-1: o+=[-1,-1]; r=r[2:]
        else: o+=[ix(r[0]),r[1]]; r=r[2:]
    return o
A={k:[res(e) for e in v] for k,v in anims.items()}
for f in glob.glob(f'{OUT}/hero8_*.webp'):
    if os.path.basename(f)[6:-5] not in SH: os.remove(f)
out={'_doc':'GENERATED by tools/anim/hero_v3_atlas.py (hero v3: idle4 walk5 run4 combo3_arc cast S1-S3 + magic circle, dash4 hurt4). anims[<name>_<dir>] = [[sheet,cell,ticks, fxSheet,fxCell ...]]: hit* = +trail fx (drawn above body); cast_s* = +back,+front magic circle (-1 = none). anchor = locked root (feet).',
     'v3':1,'figH':117,'dirs':DIRS,'sheets':[sheets[s] for s in SH],'cells':[cells[s] for s in SH],'anims':A,'cast':cast,'combo':combo,'gait':{}}
json.dump(out,open(f'{OUT}/hero8.json','w'),separators=(',',':'))
print('total KB',total//1024,'combo',combo)
